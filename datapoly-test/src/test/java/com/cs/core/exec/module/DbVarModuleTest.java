package com.cs.core.exec.module;

import com.cs.common.enums.NamingStrategyEnum;
import com.cs.common.enums.ProductTypeEnum;
import com.cs.common.exception.CommonException;
import com.cs.common.exception.ResponseErrorCode;
import com.zaxxer.hikari.HikariDataSource;
import org.junit.*;

import java.sql.Connection;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.*;

/**
 * Script-facing {@code db} module over an in-memory H2 database (MySQL mode): template
 * pipeline for every method (selectAll/selectCount/selectOne/page/insert/update/
 * batchUpdate/delete), naming-strategy conversion, pagination, the multi-dialect page
 * SQL path (OceanBase falls back to the MySQL dialect when the mode probe fails) and the
 * ${} dollar guard.
 */
public class DbVarModuleTest {

    private HikariDataSource dataSource;
    private Map<String, Object> params;

    @Before
    public void setUp() throws Exception {
        dataSource = new HikariDataSource();
        dataSource.setJdbcUrl("jdbc:h2:mem:dbVarModuleDb;MODE=MySQL;DATABASE_TO_LOWER=TRUE;DB_CLOSE_DELAY=-1");
        dataSource.setUsername("sa");
        dataSource.setPassword("");
        try (Connection connection = dataSource.getConnection(); Statement statement = connection.createStatement()) {
            statement.execute("DROP TABLE IF EXISTS t_item");
            statement.execute("CREATE TABLE t_item (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    + "item_name VARCHAR(64), price INT)");
            statement.execute("INSERT INTO t_item(item_name, price) VALUES ('apple', 4)");
            statement.execute("INSERT INTO t_item(item_name, price) VALUES ('banana', 7)");
            statement.execute("INSERT INTO t_item(item_name, price) VALUES ('cherry', 9)");
        }
        params = new HashMap<>();
    }

    @After
    public void tearDown() {
        if (null != dataSource) {
            dataSource.close();
        }
    }

    private DbVarModule module(ProductTypeEnum productType, NamingStrategyEnum strategy, boolean printSqlLog,
                               boolean dollarAllowed) {
        return new DbVarModule(dataSource, productType, params, strategy, printSqlLog, dollarAllowed);
    }

    private DbVarModule module() {
        return module(ProductTypeEnum.MYSQL, NamingStrategyEnum.CAMEL_CASE, true, true);
    }

    private int count() throws SQLException {
        try (Connection connection = dataSource.getConnection();
             Statement statement = connection.createStatement();
             ResultSet rs = statement.executeQuery("SELECT COUNT(*) FROM t_item")) {
            rs.next();
            return rs.getInt(1);
        }
    }

    @Test
    public void varModuleNameIsDb() throws Exception {
        Assert.assertEquals("db", module().getVarModuleName());
    }

    @Test
    @SuppressWarnings("unchecked")
    public void selectAllAppliesBindingAndNamingStrategy() throws SQLException {
        params.put("minPrice", 7);
        List<Map<String, Object>> rows = module().selectAll(
                "SELECT item_name, price FROM t_item <where><if test=\"minPrice != null\"> price &gt;= #{minPrice}</if></where> ORDER BY id");
        Assert.assertEquals(2, rows.size());
        // snake_case column label converted to camelCase by the CAMEL_CASE strategy
        Assert.assertEquals("banana", rows.get(0).get("itemName"));
        Assert.assertEquals(7, rows.get(0).get("price"));
    }

    @Test
    @SuppressWarnings("unchecked")
    public void selectAllPlainSqlReturnsEveryRow() throws SQLException {
        List<Map<String, Object>> rows = module().selectAll("SELECT item_name FROM t_item ORDER BY id");
        Assert.assertEquals(Arrays.asList("apple", "banana", "cherry"),
                rows.stream().map(r -> r.get("itemName")).collect(java.util.stream.Collectors.toList()));
    }

    @Test
    public void selectCountCountsWrappedQuery() throws Exception {
        params.put("maxPrice", 5);
        Integer count = module().selectCount(
                "SELECT id FROM t_item <where><if test=\"maxPrice != null\"> price &lt;= #{maxPrice}</if></where>");
        Assert.assertEquals(Integer.valueOf(1), count);
    }

    @Test
    public void selectOneReturnsFirstRowOrNull() throws Exception {
        Map<String, Object> row = module().selectOne("SELECT item_name FROM t_item WHERE id = #{id}");
        // missing parameter binds as null: no row matches
        Assert.assertNull(row);
        params.put("id", 3L);
        row = module().selectOne("SELECT item_name FROM t_item WHERE id = #{id}");
        Assert.assertEquals("cherry", row.get("itemName"));
    }

    @Test
    @SuppressWarnings("unchecked")
    public void pageFollowsApiPageConventionWithMysqlDialect() throws Exception {
        params.put("apiPageNum", 2);
        params.put("apiPageSize", 2);
        List<Map<String, Object>> rows = module().page("SELECT item_name FROM t_item ORDER BY id");
        Assert.assertEquals(1, rows.size());
        Assert.assertEquals("cherry", rows.get(0).get("itemName"));
    }

    @Test
    @SuppressWarnings("unchecked")
    public void pageOnMultiDialectTypeFallsBackToMysqlDialectWhenProbeFails() throws Exception {
        // OCEANBASE is multiDialect: the mode-probe SQL cannot run on H2, so the MySQL dialect is used
        params.put("apiPageNum", 1);
        params.put("apiPageSize", 2);
        DbVarModule oceanbase = module(ProductTypeEnum.OCEANBASE, NamingStrategyEnum.CAMEL_CASE, true, true);
        List<Map<String, Object>> rows = oceanbase.page("SELECT item_name FROM t_item ORDER BY id");
        Assert.assertEquals(2, rows.size());
        Assert.assertEquals("apple", rows.get(0).get("itemName"));
    }

    @Test
    public void insertReturnsGeneratedKeys() throws SQLException {
        params.put("name", "durian");
        params.put("price", 20);
        Map<String, Object> keys = module().insert(
                "INSERT INTO t_item(item_name, price) VALUES(#{name}, #{price})");
        Assert.assertNotNull("identity column key must come back", keys);
        Assert.assertFalse(keys.isEmpty());
        Assert.assertEquals(4, count());
    }

    @Test
    public void updateReturnsAffectedRows() throws SQLException {
        params.put("price", 99);
        int updated = module().update("UPDATE t_item SET price = #{price} WHERE item_name = 'apple'");
        Assert.assertEquals(1, updated);
        try (Connection connection = dataSource.getConnection();
             Statement statement = connection.createStatement();
             ResultSet rs = statement.executeQuery("SELECT price FROM t_item WHERE item_name = 'apple'")) {
            rs.next();
            Assert.assertEquals(99, rs.getInt(1));
        }
    }

    @Test
    public void batchUpdateRunsEachStatementThroughTemplatePipeline() throws SQLException {
        int total = module().batchUpdate(Arrays.asList(
                "INSERT INTO t_item(item_name, price) VALUES ('egg', 1)",
                "INSERT INTO t_item(item_name, price) VALUES (#{name}, #{price})"));
        Assert.assertEquals(2, total);
        Assert.assertEquals(5, count());
    }

    @Test
    public void deleteReturnsAffectedRows() throws SQLException {
        int deleted = module().delete("DELETE FROM t_item WHERE price > 5");
        Assert.assertEquals(2, deleted);
        Assert.assertEquals(1, count());
    }

    @Test
    public void beginTxReturnsTransactionHandle() throws Exception {
        TxVarModule tx = module().beginTx();
        Assert.assertEquals("tx", tx.getVarModuleName());
        tx.rollback();
        // the leftover registry must be empty afterwards: cleanup finds nothing to roll back
        TxVarModule.rollbackLeftoversOnCurrentThread();
    }

    @Test
    public void dollarSubstitutionForbiddenRejectsTemplate() throws Exception {
        params.put("col", "item_name");
        DbVarModule guarded = module(ProductTypeEnum.MYSQL, NamingStrategyEnum.CAMEL_CASE, true, false);
        try {
            guarded.selectAll("SELECT ${col} FROM t_item");
            Assert.fail("${} must be blocked when dollar substitution is not allowed");
        } catch (CommonException e) {
            Assert.assertEquals(ResponseErrorCode.ERROR_INTERNAL_ERROR, e.getCode());
        }
        // every other entry point goes through the same guard
        try {
            guarded.selectCount("SELECT ${col} FROM t_item");
            Assert.fail();
        } catch (CommonException e) {
            Assert.assertEquals(ResponseErrorCode.ERROR_INTERNAL_ERROR, e.getCode());
        }
        try {
            guarded.update("UPDATE t_item SET price = 1 WHERE item_name = '${col}'");
            Assert.fail();
        } catch (CommonException e) {
            Assert.assertEquals(ResponseErrorCode.ERROR_INTERNAL_ERROR, e.getCode());
        }
        try {
            guarded.batchUpdate(Collections.singletonList("DELETE FROM t_item WHERE item_name = '${col}'"));
            Assert.fail();
        } catch (CommonException e) {
            Assert.assertEquals(ResponseErrorCode.ERROR_INTERNAL_ERROR, e.getCode());
        }
        try {
            guarded.page("SELECT ${col} FROM t_item");
            Assert.fail();
        } catch (CommonException e) {
            Assert.assertEquals(ResponseErrorCode.ERROR_INTERNAL_ERROR, e.getCode());
        }
        try {
            guarded.selectOne("SELECT ${col} FROM t_item");
            Assert.fail();
        } catch (CommonException e) {
            Assert.assertEquals(ResponseErrorCode.ERROR_INTERNAL_ERROR, e.getCode());
        }
        try {
            guarded.insert("INSERT INTO t_item(item_name) VALUES('${col}')");
            Assert.fail();
        } catch (CommonException e) {
            Assert.assertEquals(ResponseErrorCode.ERROR_INTERNAL_ERROR, e.getCode());
        }
    }

    @Test
    @SuppressWarnings("unchecked")
    public void dollarSubstitutionAllowedRendersLiteral() throws SQLException {
        params.put("col", "item_name");
        List<Map<String, Object>> rows = module().selectAll("SELECT ${col} FROM t_item WHERE id = 1");
        Assert.assertEquals(1, rows.size());
        Assert.assertEquals("apple", rows.get(0).get("itemName"));
    }

    @Test
    public void legacyConstructorDefaultsToDollarAllowed() throws Exception {
        // the 5-arg constructor keeps the historical behavior: ${} allowed
        DbVarModule legacy = new DbVarModule(dataSource, ProductTypeEnum.MYSQL, params, NamingStrategyEnum.NONE, true);
        params.put("col", "item_name");
        Assert.assertEquals(1, legacy.selectAll("SELECT ${col} FROM t_item WHERE id = 1").size());
    }

    @Test
    public void snakeStrategyKeepsColumnLabels() throws Exception {
        DbVarModule snake = module(ProductTypeEnum.MYSQL, NamingStrategyEnum.SNAKE_CASE, false, true);
        Map<String, Object> row = snake.selectOne("SELECT item_name FROM t_item WHERE id = 1");
        Assert.assertEquals("apple", row.get("item_name"));
    }

    @Test
    public void brokenSqlSurfacesAsDataAccessException() throws Exception {
        try {
            module().selectAll("SELECT no_such_column FROM t_item");
            Assert.fail("broken SQL must fail");
        } catch (org.springframework.dao.DataAccessException expected) {
            // expected: JdbcTemplate translation
        }
    }

    @Test
    @SuppressWarnings("unchecked")
    public void quietModuleSkipsSqlLoggingOnEveryEntry() throws Exception {
        // printSqlLog=false: every db.* method runs the same pipeline without the log branch
        DbVarModule quiet = module(ProductTypeEnum.MYSQL, NamingStrategyEnum.CAMEL_CASE, false, true);

        Assert.assertEquals(3, quiet.selectAll("SELECT item_name FROM t_item ORDER BY id").size());
        Assert.assertEquals(Integer.valueOf(3), quiet.selectCount("SELECT id FROM t_item"));
        params.put("apiPageNum", 1);
        params.put("apiPageSize", 2);
        Assert.assertEquals(2, quiet.page("SELECT item_name FROM t_item ORDER BY id").size());
        params.put("name", "fig");
        params.put("price", 5);
        Assert.assertFalse(quiet.insert(
                "INSERT INTO t_item(item_name, price) VALUES(#{name}, #{price})").isEmpty());
        params.put("price", 12);
        Assert.assertEquals(1, quiet.update("UPDATE t_item SET price = #{price} WHERE item_name = 'apple'"));
        Assert.assertEquals(2, quiet.batchUpdate(Arrays.asList(
                "INSERT INTO t_item(item_name) VALUES ('grape')",
                "INSERT INTO t_item(item_name) VALUES ('kiwi')")));
        Assert.assertEquals(1, quiet.delete("DELETE FROM t_item WHERE item_name = 'apple'"));
        Assert.assertEquals(5, count());
    }

    @Test
    public void multiDialectPageWrapsConnectionFailure() throws Exception {
        // a closed pool makes the dialect-probe connection fail: wrapped as RuntimeException
        HikariDataSource closed = new HikariDataSource();
        closed.setJdbcUrl("jdbc:h2:mem:dbVarModuleClosedDb;MODE=MySQL;DATABASE_TO_LOWER=TRUE");
        closed.setUsername("sa");
        closed.setPassword("");
        closed.close();
        params.put("apiPageNum", 1);
        params.put("apiPageSize", 2);
        DbVarModule oceanbase = new DbVarModule(closed, ProductTypeEnum.OCEANBASE, params,
                NamingStrategyEnum.CAMEL_CASE, true, true);
        try {
            oceanbase.page("SELECT item_name FROM t_item");
            Assert.fail("closed datasource must fail");
        } catch (RuntimeException e) {
            Assert.assertNotNull(e.getCause());
        }
    }
}
