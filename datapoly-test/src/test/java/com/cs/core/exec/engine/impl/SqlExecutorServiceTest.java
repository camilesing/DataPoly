package com.cs.core.exec.engine.impl;

import com.cs.common.enums.NamingStrategyEnum;
import com.cs.common.enums.ProductTypeEnum;
import com.cs.common.exception.CommonException;
import com.cs.common.exception.ResponseErrorCode;
import com.cs.persistence.entity.ApiContextEntity;
import com.zaxxer.hikari.HikariDataSource;
import org.junit.*;

import java.sql.Connection;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.*;

/**
 * SQL engine over an in-memory H2 database (MySQL mode): dynamic tag rendering, #{}
 * binding, result filtering (only Collection results are returned), pagination via the
 * apiPageNum/apiPageSize convention, per-request transaction commit/rollback, the
 * ${} dollar guard and the checked/unchecked exception translation of the outer catch.
 */
public class SqlExecutorServiceTest {

    private HikariDataSource dataSource;
    private SqlExecutorService engine;

    @Before
    public void setUp() throws Exception {
        dataSource = new HikariDataSource();
        dataSource.setJdbcUrl("jdbc:h2:mem:sqlEngineDb;MODE=MySQL;DATABASE_TO_LOWER=TRUE;DB_CLOSE_DELAY=-1");
        dataSource.setUsername("sa");
        dataSource.setPassword("");
        try (Connection connection = dataSource.getConnection(); Statement statement = connection.createStatement()) {
            statement.execute("DROP TABLE IF EXISTS t_user");
            statement.execute("CREATE TABLE t_user (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    + "name VARCHAR(64), age INT)");
            statement.execute("INSERT INTO t_user(name, age) VALUES ('alice', 30)");
            statement.execute("INSERT INTO t_user(name, age) VALUES ('bob', 41)");
            statement.execute("INSERT INTO t_user(name, age) VALUES ('carol', 25)");
        }
        engine = new SqlExecutorService(dataSource, ProductTypeEnum.MYSQL);
    }

    @After
    public void tearDown() {
        if (null != dataSource) {
            dataSource.close();
        }
    }

    private static ApiContextEntity sql(String text) {
        return new ApiContextEntity(text);
    }

    private int count() throws SQLException {
        try (Connection connection = dataSource.getConnection();
             Statement statement = connection.createStatement();
             ResultSet rs = statement.executeQuery("SELECT COUNT(*) FROM t_user")) {
            rs.next();
            return rs.getInt(1);
        }
    }

    @Test
    public void selectReturnsListOfRowMaps() {
        List<Object> results = engine.execute(
                Collections.singletonList(sql("SELECT name FROM t_user WHERE id = #{id} ORDER BY id")),
                Collections.singletonMap("id", 2L), NamingStrategyEnum.CAMEL_CASE, true);
        Assert.assertEquals(1, results.size());
        List<?> rows = (List<?>) results.get(0);
        Assert.assertEquals(1, rows.size());
        Assert.assertEquals("bob", ((Map<?, ?>) rows.get(0)).get("name"));
    }

    @Test
    public void dynamicTagsRenderConditionally() {
        Map<String, Object> params = new HashMap<>();
        params.put("minAge", 40);
        List<Object> results = engine.execute(
                Collections.singletonList(sql(
                        "SELECT name FROM t_user <where><if test=\"minAge != null\"> age &gt;= #{minAge}</if></where> ORDER BY id")),
                params, NamingStrategyEnum.NONE, true);
        List<?> rows = (List<?>) results.get(0);
        Assert.assertEquals(1, rows.size());
        Assert.assertEquals("bob", ((Map<?, ?>) rows.get(0)).get("name"));
    }

    @Test
    public void dynamicTagBranchOmittedWhenParamMissing() {
        Map<String, Object> params = new HashMap<>();
        List<Object> results = engine.execute(
                Collections.singletonList(sql(
                        "SELECT name FROM t_user <where><if test=\"minAge != null\"> age &gt;= #{minAge}</if></where> ORDER BY id")),
                params, NamingStrategyEnum.NONE, true);
        Assert.assertEquals(3, ((List<?>) results.get(0)).size());
    }

    @Test
    @SuppressWarnings("unchecked")
    public void onlyCollectionResultsAreCollected() throws SQLException {
        List<Object> results = engine.execute(
                Arrays.asList(
                        sql("SELECT name FROM t_user ORDER BY id"),
                        sql("INSERT INTO t_user(name, age) VALUES ('dave', 9)"),
                        sql("UPDATE t_user SET age = 1 WHERE name = 'alice'")),
                Collections.emptyMap(), NamingStrategyEnum.NONE, true);
        // insert/update return "(n) rows affected" strings: not Collections, so not returned
        Assert.assertEquals(1, results.size());
        Assert.assertEquals(3, ((List<Map<String, Object>>) results.get(0)).size());
        // the update still executed (alice's age changed to 1)
        try (Connection connection = dataSource.getConnection();
             Statement statement = connection.createStatement();
             ResultSet rs = statement.executeQuery("SELECT age FROM t_user WHERE name = 'alice'")) {
            rs.next();
            Assert.assertEquals(1, rs.getInt(1));
        }
    }

    @Test
    public void paginationFollowsApiPageConvention() {
        Map<String, Object> params = new HashMap<>();
        params.put("apiPageNum", 2);
        params.put("apiPageSize", 2);
        List<Object> results = engine.execute(
                Collections.singletonList(sql("SELECT name FROM t_user ORDER BY id")),
                params, NamingStrategyEnum.NONE, true);
        List<?> rows = (List<?>) results.get(0);
        Assert.assertEquals(1, rows.size());
        Assert.assertEquals("carol", ((Map<?, ?>) rows.get(0)).get("name"));
    }

    @Test
    public void failureRollsBackWholeRequest() {
        try {
            engine.execute(
                    Arrays.asList(
                            sql("INSERT INTO t_user(name, age) VALUES ('ghost', 1)"),
                            sql("SELECT * FROM table_that_does_not_exist")),
                    Collections.emptyMap(), NamingStrategyEnum.NONE, true);
            Assert.fail("second statement must fail");
        } catch (RuntimeException expected) {
            Assert.assertTrue("H2 syntax error expected: " + expected.getMessage(),
                    expected.getMessage().contains("table_that_does_not_exist"));
            // rollback path taken; the first statement's insert must be undone
        }
        try {
            Assert.assertEquals(3, count());
        } catch (SQLException e) {
            throw new RuntimeException(e);
        }
    }

    @Test
    public void nonTransactionalProductTypeSkipsCommitRollback() {
        // ODPS declares offTransactional(): no setAutoCommit(false)/commit/rollback around the statements
        SqlExecutorService odpsEngine = new SqlExecutorService(dataSource, ProductTypeEnum.ODPS);
        List<Object> results = odpsEngine.execute(
                Collections.singletonList(sql("SELECT name FROM t_user WHERE id = 1")),
                Collections.emptyMap(), NamingStrategyEnum.NONE, true);
        Assert.assertEquals("alice", ((Map<?, ?>) ((List<?>) results.get(0)).get(0)).get("name"));
    }

    @Test
    public void dollarSubstitutionForbiddenWhenNotAllowed() {
        try {
            engine.execute(
                    Collections.singletonList(sql("SELECT ${col} FROM t_user")),
                    Collections.singletonMap("col", "name"), NamingStrategyEnum.NONE, false);
            Assert.fail("${} must be rejected when dollar substitution is not allowed");
        } catch (CommonException e) {
            Assert.assertEquals(ResponseErrorCode.ERROR_INTERNAL_ERROR, e.getCode());
        }
    }

    @Test
    public void dollarSubstitutionAllowedRendersLiteral() {
        List<Object> results = engine.execute(
                Collections.singletonList(sql("SELECT name FROM t_user WHERE id = 1 AND name = '${name}'")),
                Collections.singletonMap("name", "alice"), NamingStrategyEnum.NONE, true);
        Assert.assertEquals(1, ((List<?>) results.get(0)).size());
    }

    @Test
    public void checkedExceptionFromConnectionIsWrapped() {
        dataSource.close();
        try {
            engine.execute(Collections.singletonList(sql("SELECT 1")),
                    Collections.emptyMap(), NamingStrategyEnum.NONE, true);
            Assert.fail("closed pool must fail");
        } catch (RuntimeException e) {
            Assert.assertTrue("checked SQLException must be wrapped, got " + e.getClass(),
                    !(e instanceof CommonException));
            Assert.assertNotNull(e.getCause());
        }
    }
}
