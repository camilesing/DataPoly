package com.cs.core.exec.module;

import com.zaxxer.hikari.HikariDataSource;
import org.junit.*;
import org.springframework.jdbc.core.JdbcTemplate;

import java.sql.Connection;
import java.sql.Statement;

/**
 * Transaction handle of the script engine ({@code db.beginTx()}): DataSourceTransactionManager
 * semantics on the current thread, and the leftover-registry cleanup that ScriptExecutorService
 * relies on to release connections of scripts that never committed/rolled back.
 */
public class TxVarModuleTest {

    private HikariDataSource dataSource;
    private JdbcTemplate jdbcTemplate;

    @Before
    public void setUp() throws Exception {
        dataSource = new HikariDataSource();
        dataSource.setJdbcUrl("jdbc:h2:mem:txVarModuleDb;MODE=MySQL;DATABASE_TO_LOWER=TRUE;DB_CLOSE_DELAY=-1");
        dataSource.setUsername("sa");
        dataSource.setPassword("");
        try (Connection connection = dataSource.getConnection(); Statement statement = connection.createStatement()) {
            statement.execute("DROP TABLE IF EXISTS t_tx");
            statement.execute("CREATE TABLE t_tx (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    + "name VARCHAR(64))");
        }
        jdbcTemplate = new JdbcTemplate(dataSource);
    }

    @After
    public void tearDown() {
        // defensive: no leaked transaction may hold a pooled connection across tests
        TxVarModule.rollbackLeftoversOnCurrentThread();
        if (null != dataSource) {
            dataSource.close();
        }
    }

    private Integer count() {
        return jdbcTemplate.queryForObject("SELECT COUNT(*) FROM t_tx", Integer.class);
    }

    @Test
    public void varModuleNameIsTx() {
        TxVarModule tx = new TxVarModule(dataSource);
        Assert.assertEquals("tx", tx.getVarModuleName());
        tx.rollback();
    }

    @Test
    public void commitPersistsThreadBoundWrites() {
        TxVarModule tx = new TxVarModule(dataSource);
        // JdbcTemplate on the same thread joins the thread-bound transaction
        jdbcTemplate.update("INSERT INTO t_tx(name) VALUES ('kept')");
        tx.commit();
        Assert.assertEquals(Integer.valueOf(1), count());
    }

    @Test
    public void rollbackDiscardsThreadBoundWrites() {
        TxVarModule tx = new TxVarModule(dataSource);
        jdbcTemplate.update("INSERT INTO t_tx(name) VALUES ('dropped')");
        tx.rollback();
        Assert.assertEquals(Integer.valueOf(0), count());
    }

    @Test
    public void abandonedTransactionIsRolledBackByThreadCleanup() {
        TxVarModule tx = new TxVarModule(dataSource);
        jdbcTemplate.update("INSERT INTO t_tx(name) VALUES ('ghost')");
        // script never commits/rolls back: the executor's cleanup hook must roll it back
        TxVarModule.rollbackLeftoversOnCurrentThread();
        Assert.assertEquals(Integer.valueOf(0), count());
        // second cleanup finds an empty registry and returns immediately
        TxVarModule.rollbackLeftoversOnCurrentThread();
    }

    @Test
    public void cleanupSkipsAlreadyCompletedTransactions() {
        TxVarModule tx = new TxVarModule(dataSource);
        jdbcTemplate.update("INSERT INTO t_tx(name) VALUES ('kept2')");
        tx.commit();
        // committed transaction stays completed: cleanup neither rolls back nor throws
        TxVarModule.rollbackLeftoversOnCurrentThread();
        Assert.assertEquals(Integer.valueOf(1), count());
    }

    @Test
    public void sequentialTransactionsOnSameThreadAreIndependent() {
        TxVarModule first = new TxVarModule(dataSource);
        jdbcTemplate.update("INSERT INTO t_tx(name) VALUES ('a')");
        first.commit();
        TxVarModule second = new TxVarModule(dataSource);
        jdbcTemplate.update("INSERT INTO t_tx(name) VALUES ('b')");
        second.rollback();
        Assert.assertEquals(Integer.valueOf(1), count());
    }

    @Test
    public void cleanupSwallowsRollbackFailure() throws Exception {
        // dedicated db without DB_CLOSE_DELAY: closing the other connections tears the in-memory
        // database down underneath the open transaction, so the cleanup rollback fails
        HikariDataSource shortLived = new HikariDataSource();
        shortLived.setJdbcUrl("jdbc:h2:mem:txVarModuleDb2;MODE=MySQL;DATABASE_TO_LOWER=TRUE");
        shortLived.setUsername("sa");
        shortLived.setPassword("");
        try {
            try (Connection connection = shortLived.getConnection(); Statement statement = connection.createStatement()) {
                statement.execute("CREATE TABLE t_tx2 (id INT PRIMARY KEY, name VARCHAR(64))");
            }
            JdbcTemplate shortJdbc = new JdbcTemplate(shortLived);
            TxVarModule tx = new TxVarModule(shortLived);
            shortJdbc.update("INSERT INTO t_tx2(id, name) VALUES (1, 'ghost')");
            try (Connection connection = shortLived.getConnection(); Statement statement = connection.createStatement()) {
                statement.execute("SHUTDOWN");
            } catch (java.sql.SQLException ignored) {
                // the db may already be gone — either way the in-flight connection is dead
            }
            // must not throw: the failure only reaches the error log
            TxVarModule.rollbackLeftoversOnCurrentThread();
        } finally {
            shortLived.close();
        }
    }
}
